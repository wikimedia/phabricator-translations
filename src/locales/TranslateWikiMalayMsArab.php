<?php

/**
 * TranslateWiki Locale for Malay (Jawi script) localization in Phabricator
 */
final class TranslateWikiMalayMsArab extends PhutilLocale {

  public function getLocaleCode() {
    return 'ms_Arab';
  }

  public function getLocaleName() {
    // Name taken from https://translatewiki.net/wiki/Portal:Ms
    return pht('Malay (Jawi script)');
  }
}
